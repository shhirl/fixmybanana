#!/usr/bin/env python3
"""
Capture v0 receipts for /how-its-built.

Runs the SAME code path the live site uses (app.analyze_handstand_posture) and records
what it sends to OpenAI. Two outputs:

  eval/v0/prompt.md          the exact prompts/messages, always written (no API key needed)
  eval/v0/raw_response.json  one real request+response pair, written only when
                             OPENAI_API_KEY is set (costs one or two API calls)

Usage:
  .venv/bin/python eval/capture_v0.py                       # dry run: prompt.md only
  OPENAI_API_KEY=sk-... .venv/bin/python eval/capture_v0.py path/to/handstand.jpg
"""
import copy
import datetime as dt
import json as _json
import os
import sys
import time
from unittest import mock

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.chdir(ROOT)
import app  # noqa: E402  (imports the Flask app; no server is started)

OUT_DIR = os.path.join(ROOT, "eval", "v0")
PLACEHOLDER = "<base64 image omitted>"


def scrub(payload):
    """Copy of the request payload with the image bytes replaced by a placeholder."""
    p = copy.deepcopy(payload)
    for m in p["messages"]:
        if isinstance(m["content"], list):
            for part in m["content"]:
                if part.get("type") == "image_url":
                    part["image_url"]["url"] = "data:image/jpeg;base64," + PLACEHOLDER
    return p


class _Fake:
    def __init__(self, status, text):
        self.status_code, self.text = status, text

    def json(self):
        return _json.loads(self.text)


def capture(photo, live):
    calls = []
    real_post = app.requests.post

    def recording_post(url, headers=None, json=None, timeout=None):
        entry = {"url": url, "request": scrub(json)}
        t0 = time.time()
        if live:
            r = real_post(url, headers=headers, json=json, timeout=timeout)
            entry["status"] = r.status_code
            entry["latency_s"] = round(time.time() - t0, 2)
            entry["response"] = r.json() if r.status_code == 200 else r.text[:1000]
        else:
            # Dry run: pretend the classifier said "banana back" so the feedback prompt is captured too.
            content = "banana back" if not calls else "(dry run)"
            r = _Fake(200, _json.dumps({"choices": [{"message": {"content": content}}]}))
            entry["status"] = 200
            entry["response"] = "(dry run - no API call made)"
        calls.append(entry)
        return r

    patches = [mock.patch.object(app.requests, "post", recording_post)]
    if not live:
        patches.append(mock.patch.object(app.requests, "get", lambda *a, **k: _Fake(200, "{}")))
        patches.append(mock.patch.dict(os.environ, {"OPENAI_API_KEY": "dry-run"}))
    for p in patches:
        p.start()
    try:
        result = app.analyze_handstand_posture(photo)
    finally:
        for p in patches:
            p.stop()
    return calls, result


def render_prompt_md(calls):
    names = ["Call 1 - classifier (`analyze_handstand_posture`)",
             "Call 2 - coaching feedback, only when call 1 says banana back (`get_banana_back_feedback`)"]
    lines = ["# v0 prompts - verbatim, as sent by `app.py` on 2026-09-08 (tag `v0`)", "",
             "Generated by `eval/capture_v0.py` from the site's own code path. Do not hand-edit; re-run the script.",
             "", "Model list tried in order: `" + "`, `".join(
                 ["gpt-4o", "gpt-4-turbo", "gpt-4-turbo-2024-04-09"]) + "` "
             "(v0; PR #8 later appended `gpt-5.6-terra`, `gpt-5.6-sol`). First 200 response wins.", ""]
    for i, c in enumerate(calls):
        req = c["request"]
        lines += [f"## {names[i] if i < len(names) else 'Call ' + str(i + 1)}", "",
                  f"- endpoint: `{c['url']}`",
                  f"- model: `{req['model']}` · temperature: `{req['temperature']}` · max_tokens: `{req.get('max_tokens')}`",
                  ""]
        for m in req["messages"]:
            lines.append(f"### {m['role']}")
            lines.append("")
            if isinstance(m["content"], str):
                lines += ["```text", m["content"], "```"]
            else:
                for part in m["content"]:
                    if part["type"] == "text":
                        lines += ["```text", part["text"], "```"]
                    else:
                        lines.append(f"*(image attached: `{part['image_url']['url']}`)*")
            lines.append("")
    lines += ["## Post-processing of call 1 (from `app.py`)", "",
              "```text",
              "text = response.lower().strip()",
              "'banana' in text  -> label 'banana back' (form_quality='bad', then call 2 runs)",
              "'good'   in text  -> label 'good form'   (form_quality='good')",
              "otherwise         -> first line of text  (form_quality='unclear')",
              "```", ""]
    return "\n".join(lines)


def main():
    photo = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "static", "handstand_demo.jpg")
    live = bool(os.environ.get("OPENAI_API_KEY"))
    os.makedirs(OUT_DIR, exist_ok=True)
    calls, result = capture(photo, live)

    with open(os.path.join(OUT_DIR, "prompt.md"), "w") as f:
        f.write(render_prompt_md(calls))
    print(f"wrote eval/v0/prompt.md ({len(calls)} call(s) captured, live={live})")

    if live:
        out = {
            "captured_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
            "photo": os.path.relpath(photo, ROOT),
            "site_result": result,
            "calls": calls,
        }
        with open(os.path.join(OUT_DIR, "raw_response.json"), "w") as f:
            _json.dump(out, f, indent=2, ensure_ascii=False)
        print("wrote eval/v0/raw_response.json")
        print("site_result:", _json.dumps(result, ensure_ascii=False))
    else:
        print("no OPENAI_API_KEY set - dry run, raw_response.json not written")


if __name__ == "__main__":
    main()
